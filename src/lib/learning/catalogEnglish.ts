export function translateCatalogText(value: string, language: CatalogLanguage): string {
  if (language !== 'en' || !value) return value;
  const translate = (input: string): string => {
    const exact = LEARNING_CATALOG_EN[input];
    if (exact !== undefined) return exact;
    for (const [pattern, build] of CATALOG_PATTERNS) {
      const match = input.match(pattern);
      if (match) return build(match, translate);
    }
    return input;
  };
  return translate(value);
}

function localizeNode(node: KnowledgeMapNode, language: CatalogLanguage): KnowledgeMapNode {
  const tr = (value: string) => translateCatalogText(value, language);
  return {
    ...node,
    title: tr(node.title),
    description: node.description ? tr(node.description) : node.description,
    category: node.category ? tr(node.category) : node.category,
    prerequisites: node.prerequisites.map((item) => ({ ...item, title: tr(item.title) })),
    exercises: node.exercises.map((exercise) => ({ ...exercise, title: tr(exercise.title) })),
  };
}

function localizePath(path: LearningPathSummary, language: CatalogLanguage): LearningPathSummary {
  return {
    ...path,
    title: translateCatalogText(path.title, language),
    description: path.description
      ? translateCatalogText(path.description, language)
      : path.description,
  };
}

/** Display copy of the knowledge map in the chosen language; ids and slugs are untouched. */
export function localizeKnowledgeMap(
  data: KnowledgeMapData,
  language: CatalogLanguage
): KnowledgeMapData {
  if (language !== 'en') return data;
  return {
    ...data,
    nodes: data.nodes.map((node) => localizeNode(node, language)),
    paths: data.paths.map((path) => localizePath(path, language)),
  };
}
