import { readFile, writeFile } from 'node:fs/promises';
import fontkit from '@pdf-lib/fontkit';
import { format, resolveConfig } from 'prettier';

// Sora is bundled and licensed under OFL; no installed OS fonts enter this output.
const font = fontkit.create(await readFile('public/assets/credentials/Sora-Bold.ttf'));
const labels = [
  'PRIMEIRO PASSO',
  'SEÇÃO CONCLUÍDA',
  'CURSO CONCLUÍDO',
  'PRÁTICA CONCLUÍDA',
  'TRILHA CONCLUÍDA',
  'CONQUISTA',
];
const commands = {
  moveTo: 'M',
  lineTo: 'L',
  quadraticCurveTo: 'Q',
  bezierCurveTo: 'C',
  closePath: 'Z',
};
const number = (value) => String(Number(value.toFixed(3)));
const lettering = {};
for (const label of labels) {
  const run = font.layout(label);
  if (run.glyphs.some((glyph) => glyph.id === 0)) throw new Error(`Missing Sora glyph in ${label}`);
  const scale = 10 / font.unitsPerEm;
  const tracking = 0.3;
  const width =
    run.positions.reduce((sum, position) => sum + position.xAdvance * scale, 0) +
    (run.glyphs.length - 1) * tracking;
  if (width > 148) throw new Error(`Ribbon label does not fit: ${label}`);
  let pen = 120 - width / 2;
  let path = '';
  run.glyphs.forEach((glyph, index) => {
    const position = run.positions[index];
    for (const command of glyph.path.commands) {
      const svg = commands[command.command];
      if (!svg) throw new Error(`Unsupported font outline command: ${command.command}`);
      path +=
        svg +
        command.args
          .map((value, axis) =>
            number(
              axis % 2 === 0
                ? pen + (value + position.xOffset) * scale
                : 191 - (value + position.yOffset) * scale
            )
          )
          .join(' ');
    }
    pen += position.xAdvance * scale + tracking;
  });
  lettering[label] = path;
}
const output = 'src/lib/credentials/badge-lettering.ts';
const source = await format(
  '/** Generated by scripts/build-credential-badge-lettering.mjs from bundled Sora-Bold.ttf.\n' +
    ' * Sora: SIL Open Font License (public/brand/OFL-Sora.txt). Rebuild; do not edit outlines.\n' +
    ' * Glyph outlines keep badge ribbons readable in fontless server/PDF rasterizers. */\n' +
    'export const credentialRibbonOutlines = ' +
    JSON.stringify(lettering, null, 2) +
    ' as const;\n',
  { ...(await resolveConfig(output)), filepath: output }
);
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== source)
    throw new Error('Badge lettering needs rebuilding.');
  console.log('Badge lettering matches the bundled Sora font.');
} else {
  await writeFile(output, source);
  console.log(`Generated ${labels.length} font-independent badge ribbon labels.`);
}
