import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

// Trace the supplied artwork once; the product renders a small, static vector.
const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/build-brand-assets.mjs <monogram.png>');
const { data, info } = await sharp(source)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });
const { width: w, height: h } = info;
const mask = new Uint8Array(w * h);
for (let i = 0; i < mask.length; i++)
  mask[i] = Number(data[i * 4 + 3] > 160 && data[i * 4 + 2] > 100);
const seen = new Uint8Array(mask.length);
let largest = [];
for (let start = 0; start < mask.length; start++) {
  if (!mask[start] || seen[start]) continue;
  const queue = [start];
  seen[start] = 1;
  for (let j = 0; j < queue.length; j++) {
    const p = queue[j],
      x = p % w;
    for (const q of [x ? p - 1 : -1, x < w - 1 ? p + 1 : -1, p - w, p + w]) {
      if (q >= 0 && q < mask.length && mask[q] && !seen[q]) {
        seen[q] = 1;
        queue.push(q);
      }
    }
  }
  if (queue.length > largest.length) largest = queue;
}
const main = new Uint8Array(mask.length);
for (const p of largest) main[p] = 1;
const edges = new Map();
const edge = (x1, y1, x2, y2) => edges.set(`${x1},${y1}`, [x2, y2]);
for (const p of largest) {
  const x = p % w,
    y = Math.floor(p / w);
  if (!y || !main[p - w]) edge(x, y, x + 1, y);
  if (x === w - 1 || !main[p + 1]) edge(x + 1, y, x + 1, y + 1);
  if (y === h - 1 || !main[p + w]) edge(x + 1, y + 1, x, y + 1);
  if (!x || !main[p - 1]) edge(x, y + 1, x, y);
}
let contour = [];
while (edges.size) {
  const start = edges.keys().next().value;
  let key = start;
  const points = [];
  while (edges.has(key)) {
    points.push(key.split(',').map(Number));
    const next = edges.get(key);
    edges.delete(key);
    key = next.join(',');
    if (key === start) break;
  }
  if (points.length > contour.length) contour = points;
}
function simplify(points, tolerance) {
  if (points.length < 3) return points;
  const a = points[0],
    b = points.at(-1),
    dx = b[0] - a[0],
    dy = b[1] - a[1];
  let max = 0,
    index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const t = Math.max(
      0,
      Math.min(
        1,
        ((points[i][0] - a[0]) * dx + (points[i][1] - a[1]) * dy) / (dx * dx + dy * dy || 1)
      )
    );
    const distance = Math.hypot(points[i][0] - a[0] - t * dx, points[i][1] - a[1] - t * dy);
    if (distance > max) {
      max = distance;
      index = i;
    }
  }
  return max > tolerance
    ? [
        ...simplify(points.slice(0, index + 1), tolerance).slice(0, -1),
        ...simplify(points.slice(index), tolerance),
      ]
    : [a, b];
}
const middle = Math.floor(contour.length / 2);
const points = [
  ...simplify(contour.slice(0, middle + 1), 3).slice(0, -1),
  ...simplify([...contour.slice(middle), contour[0]], 3).slice(0, -1),
];
const minX = Math.min(...points.map((p) => p[0])),
  minY = Math.min(...points.map((p) => p[1]));
const width = Math.max(...points.map((p) => p[0])) - minX,
  height = Math.max(...points.map((p) => p[1])) - minY;
const normalized = points.map(([x, y]) => [x - minX + 4, y - minY + 4]);
const f = (n) => +n.toFixed(2);
let d = `M${normalized[0].join(' ')}`;
for (let i = 0; i < normalized.length; i++) {
  const p0 = normalized[(i - 1 + normalized.length) % normalized.length],
    p1 = normalized[i],
    p2 = normalized[(i + 1) % normalized.length],
    p3 = normalized[(i + 2) % normalized.length];
  const chord = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
  const handle1 = (Math.min(chord(p0, p1), chord(p1, p2)) * 0.28) / (chord(p0, p2) || 1);
  const handle2 = (Math.min(chord(p1, p2), chord(p2, p3)) * 0.28) / (chord(p1, p3) || 1);
  d += `C${f(p1[0] + (p2[0] - p0[0]) * handle1)} ${f(p1[1] + (p2[1] - p0[1]) * handle1)} ${f(p2[0] - (p3[0] - p1[0]) * handle2)} ${f(p2[1] - (p3[1] - p1[1]) * handle2)} ${p2.join(' ')}`;
}
d += 'Z';
const viewBox = `0 0 ${width + 8} ${height + 8}`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none"><title>Stacklyst</title><path d="${d}" fill="#0083fe"/></svg>\n`;
await fs.mkdir('public/brand', { recursive: true });
for (const file of [
  'public/brand/monogram.svg',
  'public/logo.svg',
  'public/logo-light.svg',
  'src/app/icon.svg',
])
  await fs.writeFile(file, svg);
const geometry = `// Traced from the supplied Stacklyst S. Generated by scripts/build-brand-assets.mjs.\nexport const brandGeometry = ${JSON.stringify({ viewBox, width: width + 8, height: height + 8, path: d }, null, 2)} as const;\n`;
for (const file of ['src/lib/brand-geometry.ts', 'apps/mobile/src/components/brand-geometry.ts'])
  await fs.writeFile(file, geometry);
for (const file of [
  'public/logo.png',
  'public/logo-light.png',
  'public/apple-touch-icon.png',
  'src/app/icon.png',
  'apps/mobile/assets/logo.png',
]) {
  const size = file.includes('apple') ? 180 : 512;
  await sharp(Buffer.from(svg)).resize(size, size, { fit: 'contain' }).png().toFile(file);
}
for (const [file, mark, background, monochrome] of [
  ['app-icon.png', 700, '#08090b', false],
  ['android-icon-foreground.png', 600, '#00000000', false],
  ['android-icon-monochrome.png', 600, '#00000000', true],
  ['splash-icon.png', 800, '#00000000', false],
]) {
  const icon = await sharp(Buffer.from(monochrome ? svg.replace('#0083fe', '#ffffff') : svg))
    .resize(mark, mark, { fit: 'contain' })
    .png()
    .toBuffer();
  await sharp({ create: { width: 1024, height: 1024, channels: 4, background } })
    .composite([{ input: icon, gravity: 'center' }])
    .png()
    .toFile(path.join('apps/mobile/assets', file));
}
// Next's file-convention favicon takes precedence over metadata.
const png = await sharp(Buffer.from(svg)).resize(48, 48, { fit: 'contain' }).png().toBuffer();
const header = Buffer.alloc(22);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(1, 4);
header[6] = 48;
header[7] = 48;
header.writeUInt16LE(1, 10);
header.writeUInt16LE(32, 12);
header.writeUInt32LE(png.length, 14);
header.writeUInt32LE(22, 18);
await fs.writeFile('src/app/favicon.ico', Buffer.concat([header, png]));
console.log(
  `Brand assets generated: ${normalized.length} contour points, ${Buffer.byteLength(svg)} byte SVG.`
);
