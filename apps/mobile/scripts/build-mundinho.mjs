import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const sharp = require('sharp');
const assets = {};
for (const file of [
  ...['', '-idle', '-attack', '-bow'].flatMap((suffix) =>
    [
      'body',
      'outfit',
      'eyes',
      'hair',
      'accessory',
      ...(['-attack', '-bow'].includes(suffix) ? ['weapon'] : []),
    ].map((layer) => 'hero-' + layer + suffix + '.png')
  ),
  'forest.png',
  'blue-clearing.png',
  'blue-meadow.png',
  'blue-forest-fringe.png',
  'blue-grove.png',
  'blue-rocks.png',
  'chest.png',
  'blue-arena.png',
  'blue-stairs.png',
  'blue-rift.png',
  'boss-veil.png',
  'boss-projectile.png',
  'challenge-objects.png',
  'blue-battle.png',
  'combat-effects.png',
  'equipment.png',
  'blue-sign.png',
  'habitats-back.png',
  'habitats-front.png',
  'portrait-body.png',
  'portrait-outfit.png',
  'portrait-eyes.png',
  'portrait-hair-back.png',
  'portrait-hair.png',
  'portrait-accessory.png',
  'blue-creatures.png',
  'python.svg',
  'js.svg',
  'ts.svg',
  'rust.svg',
  'go.svg',
  'java.svg',
]) {
  const bytes = await readFile(path.resolve('public/assets/mundinho', file));
  assets[file] = ['forest.png', 'blue-meadow.png', 'blue-clearing.png', 'blue-arena.png'].includes(
    file
  )
    ? `data:image/webp;base64,${(await sharp(bytes).webp({ quality: 85 }).toBuffer()).toString('base64')}`
    : `data:${file.endsWith('.png') ? 'image/png' : 'image/svg+xml'};base64,${bytes.toString('base64')}`;
}
const audioManifest = JSON.parse(
  await readFile(path.resolve('public/assets/mundinho/audio/manifest.json'), 'utf8')
);
for (const { file } of audioManifest.assets) {
  const bytes = await readFile(path.resolve('public/assets/mundinho/audio', file));
  assets[`audio/${file}`] = `data:audio/mpeg;base64,${bytes.toString('base64')}`;
}
const result = await build({
  entryPoints: ['apps/mobile/src/mundinho/entry.tsx'],
  bundle: true,
  write: false,
  minify: true,
  format: 'iife',
  platform: 'browser',
  // Shared web components and the native entry must use the same React runtime.
  // Otherwise esbuild resolves the mobile and root installations separately.
  alias: {
    react: path.dirname(require.resolve('react/package.json')),
    'react-dom': path.dirname(require.resolve('react-dom/package.json')),
  },
  target: 'es2020',
  external: ['/assets/mundinho/pixelify-sans.ttf'],
  outfile: 'mundinho.js',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
});
const js = result.outputFiles
  .find((f) => f.path.endsWith('.js'))
  .text.replaceAll('</script', '<\\/script');
const font = await readFile(path.resolve('public/assets/mundinho/pixelify-sans.ttf'));
const fontLicense = await readFile(
  path.resolve('public/assets/mundinho/LICENSE-Pixelify-Sans.txt'),
  'utf8'
);
const css = result.outputFiles
  .find((f) => f.path.endsWith('.css'))
  .text.replaceAll(
    '/assets/mundinho/pixelify-sans.ttf',
    `data:font/ttf;base64,${font.toString('base64')}`
  );
const html = `<!doctype html><html lang="pt-BR"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; font-src data:; connect-src 'none';"><style>/* ${fontLicense} */body{margin:0;background:#070a0e;font-family:system-ui,sans-serif}button{font-family:inherit}${css}</style></head><body><div id="root"></div><script>globalThis.__MUNDINHO_ASSETS__=${JSON.stringify(assets)};${js}</script></body></html>`;
await mkdir('apps/mobile/src/mundinho', { recursive: true });
await writeFile(
  'apps/mobile/src/mundinho/document.generated.ts',
  '// Generated by scripts/build-mundinho.mjs. No credentials or user data.\nexport const mundinhoHtml = ' +
    JSON.stringify(html) +
    ';\n'
);
console.log(
  `Mundinho bundled: ${Math.round(html.length / 1024)} KiB, offline artwork and authenticated native bridge.`
);
